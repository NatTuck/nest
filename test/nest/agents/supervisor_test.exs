defmodule Nest.Agents.SupervisorTest do
  @moduledoc """
  Tests for the unified `Supervisor.fetch_or_start_agent/1`
  entry point and the supporting `start_agent/1`,
  `stop_agent/1`, `list_agents/0`, and `get_agent/1`
  functions.

  The new flow:

    * `fetch_or_start_agent/1` — single function for both
      "start new" and "on-demand-load" paths. The DB is the
      source of truth for "does this name exist?".
    * `Agents.create_agent/2` — standard caller interface
      that runs `Agent.pre_spawn/1` (DB row + system
      message) in the caller's pid, then calls
      `Supervisor.fetch_or_start_agent/1` to spawn the
      GenServer under the supervisor.

  Persistence is **enabled** in the test env (see
  `config/test.exs`). All tests in this module are
  `async: true` and run against a `DataCase` sandbox.
  """
  use Nest.DataCase, async: true

  alias Nest.Agents
  alias Nest.Agents.AgentTestHelpers
  alias Nest.Agents.Registry
  alias Nest.Agents.Supervisor
  alias Nest.Persistence

  setup do
    # Note: we deliberately do NOT call `Supervisor.stop_agent/1`
    # on every existing agent here. With `async: true`, that would
    # kill agents created by other concurrent tests (e.g. the
    # channel tests' per-test agents), which then fail with
    # "agent not found" at subscribe_and_join. Per-test cleanup
    # belongs in the test that owns the agent, not in a shared
    # setup block.
    #
    # We also don't wipe /tmp/nest-VMPID/ because the path is
    # shared across all tests in this BEAM VM and wiping in setup
    # races with concurrent async tests' agents. Per-agent cleanup
    # is the agent's own responsibility in `terminate/2`.

    # No `await_models_refresh/0` needed: this file's tests
    # either use `qwen3.5-plus` (a static-config entry, returned
    # immediately by `Models.list/0` from `state.static_config.models`)
    # or pass `%{provider: "model-studio"}` without a `:name` to
    # force the auto-name path (which starts the agent in
    # `:model_missing` by design).

    {:ok, _space_id} = AgentTestHelpers.create_test_space()
    :ok
  end

  defp fresh_name, do: "agent#{System.unique_integer([:positive])}"

  describe "start_pre_spawned/3" do
    test "passes a successful start through and removes nothing" do
      space_id = AgentTestHelpers.current_space_id()
      name = fresh_name()
      {:ok, ours} = Persistence.insert_agent(attrs_for(space_id, name))

      assert {:ok, ^name} =
               Supervisor.start_pre_spawned(attrs_for(space_id, name), ours.id, fn ->
                 {:ok, name}
               end)

      assert {:ok, _row} = Persistence.fetch_agent(space_id, name)
    end

    test "cleans up and re-raises when the start raises" do
      space_id = AgentTestHelpers.current_space_id()
      name = fresh_name()
      {:ok, ours} = Persistence.insert_agent(attrs_for(space_id, name))

      # The rollback logs a warning naming the row it removed; capture it so
      # the suite's output stays clean.
      ExUnit.CaptureLog.capture_log(fn ->
        assert_raise RuntimeError, "boom", fn ->
          Supervisor.start_pre_spawned(attrs_for(space_id, name), ours.id, fn -> raise "boom" end)
        end
      end)

      # The exception is the caller's to report, and the row is gone with it.
      assert Persistence.fetch_agent(space_id, name) == {:error, :not_found}
    end

    test "cannot remove a row it did not insert, even when the name is reused" do
      # The cleanup deletes by `id`, never by name. Our own row can only be
      # removed by us, and the name only becomes free *after* that — so a row
      # holding the same name is necessarily someone else's, and must survive
      # even though this call is rolling back a failure for that name.
      space_id = AgentTestHelpers.current_space_id()
      name = fresh_name()

      {:ok, ours} = Persistence.insert_agent(attrs_for(space_id, name))
      Persistence.delete_agent_by_id(ours.id)
      {:ok, theirs} = Persistence.insert_agent(attrs_for(space_id, name))
      refute theirs.id == ours.id

      ExUnit.CaptureLog.capture_log(fn ->
        assert {:error, :boom} =
                 Supervisor.start_pre_spawned(attrs_for(space_id, name), ours.id, fn ->
                   {:error, :boom}
                 end)
      end)

      assert {:ok, %{id: id}} = Persistence.fetch_agent(space_id, name)
      assert id == theirs.id
    end
  end

  defp attrs_for(space_id, name) do
    %{
      name: name,
      space_id: space_id,
      model: test_model(),
      vocation_id: AgentTestHelpers.vocation_id_for_test()
    }
  end

  defp test_model, do: %{name: "qwen3.5-plus", provider: "model-studio"}

  describe "fetch_or_start_agent/1" do
    test "starts an agent with an autogenerated name" do
      # The supervisor no longer auto-generates names — that
      # responsibility moved to `Agents.create_agent/2`, which
      # calls `Supervisor.generate_unique_name/0` when the
      # caller didn't supply a name (and the model map's
      # `:name` is the LLM identifier, not the agent's
      # registry key). Use a model without a `:name` to
      # force the generator path.
      {{:ok, name}, _log} =
        ExUnit.CaptureLog.with_log(fn ->
          Agents.create_agent(AgentTestHelpers.current_space_id(), %{provider: "model-studio"},
            vocation_id: AgentTestHelpers.vocation_id_for_test()
          )
        end)

      AgentTestHelpers.ensure_cleanup(name)

      assert Regex.match?(~r/^[a-z]+-[a-z]+$/, name)
      assert {:ok, _pid} = Registry.lookup(AgentTestHelpers.current_space_id(), name)
    end

    test "starts an agent with an explicit name" do
      name = fresh_name()

      {:ok, ^name} =
        Agents.create_agent(AgentTestHelpers.current_space_id(), test_model(),
          name: name,
          vocation_id: AgentTestHelpers.vocation_id_for_test()
        )

      AgentTestHelpers.ensure_cleanup(name)

      assert {:ok, _pid} = Registry.lookup(AgentTestHelpers.current_space_id(), name)
    end
  end

  describe "stop_agent/1" do
    test "stops agent and removes from registry" do
      name = fresh_name()

      {:ok, ^name} =
        Agents.create_agent(AgentTestHelpers.current_space_id(), test_model(),
          name: name,
          vocation_id: AgentTestHelpers.vocation_id_for_test()
        )

      AgentTestHelpers.ensure_cleanup(name)

      assert {:ok, pid} = Registry.lookup(AgentTestHelpers.current_space_id(), name)
      assert Process.alive?(pid)

      # `stop_agent/2` fires `Process.exit/2` and returns before the process
      # is gone, so the `:DOWN` — subscribed before the stop, so it cannot be
      # missed — is the event that says the process has actually exited.
      ref = Process.monitor(pid)
      :ok = Supervisor.stop_agent(AgentTestHelpers.current_space_id(), name)
      assert_receive {:DOWN, ^ref, :process, ^pid, _}, 1_000

      # The registry's auto-cleanup runs in the partition server's
      # `handle_info({:EXIT, pid, _})`: asynchronous, announcing nothing, and
      # not ordered by the `:DOWN` above (measured: ~27% of exits are still in
      # the table right after it). `:sys.get_state/2` on that partition is the
      # barrier that drains it — the link `:EXIT` is enqueued before the
      # `:DOWN` we waited on — so the lookup below reads a decided state
      # instead of polling for it.
      #
      # The partition name is `Registry.Partition.pid_name/2`'s; the registry
      # is single-partition (`Nest.Agents.Registry.child_spec/0` passes no
      # `:partitions`).
      _ = :sys.get_state(Nest.Agents.Registry.PIDPartition0, 1_000)

      assert Registry.lookup(AgentTestHelpers.current_space_id(), name) ==
               {:error, :not_found}
    end

    test "returns error for non-existent agent" do
      assert {:error, :not_found} =
               Supervisor.stop_agent(AgentTestHelpers.current_space_id(), "nonexistent")
    end
  end

  describe "list_agents/0" do
    test "returns list of running agent names" do
      name1 = fresh_name()
      name2 = fresh_name()
      vid = AgentTestHelpers.vocation_id_for_test()

      {:ok, ^name1} =
        Agents.create_agent(AgentTestHelpers.current_space_id(), test_model(),
          name: name1,
          vocation_id: vid
        )

      AgentTestHelpers.ensure_cleanup(name1)

      {:ok, ^name2} =
        Agents.create_agent(AgentTestHelpers.current_space_id(), test_model(),
          name: name2,
          vocation_id: vid
        )

      AgentTestHelpers.ensure_cleanup(name2)

      # In async mode, other tests may have started/stopped agents
      # concurrently. Assert on this test's own names (definitely
      # present) and an inclusive lower bound on the total — not
      # an exact count.
      agents = Agents.list_agents_for_space(AgentTestHelpers.current_space_id())
      assert name1 in agents
      assert name2 in agents
      assert length(agents) >= 2
    end

    # The "returns empty list when no agents" test is not expressible
    # in async mode (other tests' agents leak in). It would belong
    # in a separate `async: false` describe block or a dedicated
    # module. Tracked as future work.
  end

  describe "get_agent/1" do
    test "returns agent PID by name" do
      name = fresh_name()

      {:ok, ^name} =
        Agents.create_agent(AgentTestHelpers.current_space_id(), test_model(),
          name: name,
          vocation_id: AgentTestHelpers.vocation_id_for_test()
        )

      AgentTestHelpers.ensure_cleanup(name)

      assert {:ok, pid} = Supervisor.get_agent(AgentTestHelpers.current_space_id(), name)
      assert is_pid(pid)
      assert Process.alive?(pid)
    end

    test "returns error for non-existent name" do
      assert {:error, :not_found} =
               Supervisor.get_agent(
                 AgentTestHelpers.current_space_id(),
                 "nonexistent-#{System.unique_integer([:positive])}"
               )
    end
  end

  # Persistence-enabled regression coverage lives in
  # `test/nest/agents/supervisor_persistence_test.exs` — that
  # test module owns a `DataCase` sandbox and exercises the
  # supervisor's DB-driven flow directly.
end
